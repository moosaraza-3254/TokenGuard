/**
 * core/analyzer.js
 * TokenGuard rule engine. Pure logic: no DOM, no network.
 *
 * Every finding has the same shape:
 *   { id, title, severity, description, recommendation, reference }
 */

export const SEVERITY_WEIGHTS = { critical: 40, high: 25, medium: 10, low: 3, info: 0 };
export const SEVERITY_ORDER = ['critical', 'high', 'medium', 'low', 'info'];

const DAY = 86400;
const YEAR = 365 * DAY;

const SENSITIVE_HIGH = ['password', 'passwd', 'pwd', 'secret', 'ssn', 'credit', 'cvv', 'card'];
const SENSITIVE_MED = ['phone', 'email', 'address', 'dob', 'birth'];

function finding(id, title, severity, description, recommendation, reference) {
    return { id, title, severity, description, recommendation, reference };
}

/**
 * @param {object} input
 * @param {object} input.header
 * @param {object} input.payload
 * @param {{checked:boolean, valid:boolean}|null} [input.signature] - result of verifying with the user's key
 * @param {string|null} [input.weakSecret] - a guessable secret that signs this token, if one was found
 * @param {boolean} [input.keyIsPem] - true if the supplied key looks like a PEM public key
 * @param {number} [input.now] - current unix time in seconds (injectable for tests)
 * @returns {{ findings: object[], score: number, level: string, counts: object }}
 */
export function analyzeToken({
    header = {},
    payload = {},
    signature = null,
    weakSecret = null,
    keyIsPem = false,
    now = Math.floor(Date.now() / 1000),
} = {}) {
    const f = [];
    const alg = typeof header.alg === 'string' ? header.alg : '';
    const algUpper = alg.toUpperCase();

    // ── Algorithm ──────────────────────────────────────────────────────────────
    if (!alg || algUpper === 'NONE') {
        f.push(finding('ALG_NONE', 'Unsigned token ("none" or missing algorithm)', 'critical',
            'The header declares no signing algorithm, so anyone can create or modify this token and a careless server will accept it.',
            'Reject tokens with alg "none". Configure the server with an allow-list of expected algorithms.',
            'RFC 8725 §2.1, §3.1'));
    }

    if (algUpper.startsWith('HS') && weakSecret) {
        f.push(finding('WEAK_SECRET', 'Weak HMAC secret', 'critical',
            'This token is signed with a guessable secret that appears in a short list of commonly used secrets. An attacker can forge any token.',
            'Use a random secret of at least 256 bits, generated by a cryptographic random generator, and rotate the current one.',
            'RFC 8725 §3.5; RFC 7518 §3.2'));
    }

    if (algUpper.startsWith('HS') && keyIsPem) {
        f.push(finding('ALG_CONFUSION', 'Possible algorithm confusion', 'critical',
            'The token uses an HMAC algorithm but a public-key (PEM) key was supplied. This is the pattern of an algorithm-confusion attack, where a public key is used as an HMAC secret.',
            'Pin the expected algorithm per key on the server. Never let the token header choose how a key is used.',
            'RFC 8725 §2.1, §3.1'));
    }

    if (!header.typ) {
        f.push(finding('TYP_MISSING', 'Missing "typ" header', 'low',
            'The header has no explicit type, which makes it easier to confuse this token with another kind of JWT.',
            'Set typ (for example "JWT" or "at+jwt") and check it when validating.',
            'RFC 8725 §3.11'));
    }

    // ── Header injection vectors ───────────────────────────────────────────────
    for (const h of ['jku', 'x5u', 'jwk']) {
        if (header[h] !== undefined) {
            f.push(finding(`HEADER_${h.toUpperCase()}`, `Header "${h}" present`, 'high',
                `The token header carries a "${h}" value that tells the server where to get, or which, verification key to use. If the server trusts it, an attacker can supply their own key.`,
                `Ignore "${h}" from the token, or only accept values from a fixed allow-list of trusted URLs or keys.`,
                'RFC 8725 §3.10'));
        }
    }
    if (header.kid !== undefined) {
        f.push(finding('HEADER_KID', 'Header "kid" present', 'medium',
            'The "kid" value selects a key. If the server uses it in a file path or database query without validation, it can lead to injection.',
            'Treat kid as untrusted input: validate it and look it up only in a fixed key set.',
            'RFC 8725 §3.10'));
    }

    // ── Signature ──────────────────────────────────────────────────────────────
    if (signature && signature.checked) {
        if (!signature.valid) {
            f.push(finding('SIG_INVALID', 'Signature does not verify', 'critical',
                'The signature does not match the supplied key. The token was altered, or was signed with a different key.',
                'Reject this token. Check that the correct key and algorithm are used for verification.',
                'RFC 8725 §3.3'));
        }
    } else {
        f.push(finding('SIG_UNVERIFIED', 'Signature not verified', 'info',
            'No key was supplied, so the signature was not checked. Decoding alone does not prove the token is genuine.',
            'Supply the secret or public key to verify the signature.',
            'RFC 7519 §7.2'));
    }

    // ── Time claims ────────────────────────────────────────────────────────────
    const isNum = (v) => typeof v === 'number' && Number.isFinite(v);

    if (!isNum(payload.exp)) {
        f.push(finding('NO_EXP', 'No expiry ("exp") claim', 'high',
            'The token never expires, so a stolen token stays usable forever.',
            'Always set a short expiry (minutes for access tokens) and validate it.',
            'RFC 7519 §4.1.4; OWASP JWT Cheat Sheet'));
    } else {
        if (payload.exp < now) {
            f.push(finding('EXPIRED', 'Token has expired', 'high',
                'The expiry time is in the past. A correctly configured server will reject this token.',
                'Request a new token. Make sure the server enforces exp.',
                'RFC 7519 §4.1.4'));
        }
        const start = isNum(payload.iat) ? payload.iat : now;
        const lifetime = payload.exp - start;
        if (lifetime > YEAR) {
            f.push(finding('LONG_LIFETIME', 'Lifetime longer than 1 year', 'medium',
                'A very long lifetime gives an attacker a very long window to use a stolen token.',
                'Use short-lived access tokens and refresh tokens that can be revoked.',
                'OWASP JWT Cheat Sheet'));
        } else if (lifetime > DAY) {
            f.push(finding('LONG_LIFETIME', 'Lifetime longer than 24 hours', 'low',
                'A long lifetime gives an attacker more time to use a stolen token.',
                'Prefer lifetimes of minutes to a few hours for access tokens.',
                'OWASP JWT Cheat Sheet'));
        }
        if (isNum(payload.iat) && payload.exp < payload.iat) {
            f.push(finding('EXP_BEFORE_IAT', 'Expiry is before issue time', 'medium',
                'The token expires before it was issued, which suggests a bug or tampering.',
                'Check the code that issues tokens, and reject tokens with inconsistent times.',
                'RFC 7519 §4.1.4, §4.1.6'));
        }
    }
    if (isNum(payload.nbf) && payload.nbf > now) {
        f.push(finding('NBF_FUTURE', '"nbf" is in the future', 'medium',
            'The token is not valid yet. It may be a clock-skew problem or a crafted token.',
            'Check clock synchronisation and enforce nbf with a small leeway.',
            'RFC 7519 §4.1.5'));
    }
    if (isNum(payload.iat) && payload.iat > now) {
        f.push(finding('IAT_FUTURE', '"iat" is in the future', 'medium',
            'The token claims to be issued in the future, which suggests clock skew or a forged token.',
            'Check clock synchronisation between issuer and verifier.',
            'RFC 7519 §4.1.6'));
    }

    // ── Identity claims ────────────────────────────────────────────────────────
    if (!payload.iss) {
        f.push(finding('MISSING_ISS', 'Missing issuer ("iss")', 'medium',
            'Without an issuer the server cannot check who created the token.',
            'Set iss and validate it against the expected issuer.',
            'RFC 8725 §3.8; RFC 7519 §4.1.1'));
    }
    if (!payload.aud) {
        f.push(finding('MISSING_AUD', 'Missing audience ("aud")', 'medium',
            'Without an audience the token could be accepted by a service it was never meant for.',
            'Set aud and make every service check that it is in the audience.',
            'RFC 8725 §3.9; RFC 7519 §4.1.3'));
    }
    if (!payload.jti) {
        f.push(finding('MISSING_JTI', 'Missing token ID ("jti")', 'low',
            'Without a unique ID the token cannot be individually revoked or checked for replay.',
            'Add a unique jti if you need revocation or replay protection.',
            'RFC 7519 §4.1.7'));
    }

    // ── Content ────────────────────────────────────────────────────────────────
    const keys = Object.keys(payload).map((k) => k.toLowerCase());
    const hi = SENSITIVE_HIGH.filter((s) => keys.some((k) => k.includes(s)));
    const med = SENSITIVE_MED.filter((s) => keys.some((k) => k.includes(s)));
    if (hi.length || med.length) {
        f.push(finding('SENSITIVE_DATA', 'Sensitive data in payload', hi.length ? 'high' : 'medium',
            `The payload is only encoded, not encrypted, so anyone holding the token can read it. Fields that look sensitive: ${[...hi, ...med].join(', ')}.`,
            'Keep personal or secret data out of the token. Store it server-side, or use encrypted tokens (JWE).',
            'RFC 7519 §12; OWASP JWT Cheat Sheet'));
    }

    // ── Order, score, level ────────────────────────────────────────────────────
    f.sort((a, b) => SEVERITY_ORDER.indexOf(a.severity) - SEVERITY_ORDER.indexOf(b.severity));

    const counts = { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
    let score = 0;
    for (const x of f) {
        counts[x.severity] += 1;
        score += SEVERITY_WEIGHTS[x.severity];
    }
    score = Math.min(100, score);
    // Any single critical finding means the token cannot be trusted: never rate it below 80.
    if (counts.critical > 0) score = Math.max(score, 80);

    return { findings: f, score, level: scoreToLevel(score), counts };
}

export function scoreToLevel(score) {
    if (score >= 80) return 'Critical';
    if (score >= 50) return 'High';
    if (score >= 20) return 'Medium';
    return 'Low';
}